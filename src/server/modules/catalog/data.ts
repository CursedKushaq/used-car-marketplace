// Helper to assemble full listings with computed price ratings and verification ladders
export function getSeedListings(): CarListing[] {
  // Group by make & model to find comparison pools
  const compPools = new Map<string, number[]>();

  for (const car of RAW_CAR_DATA) {
    const key = `${car.make}:${car.model}`;
    if (!compPools.has(key)) {
      compPools.set(key, []);
    }
    compPools.get(key)!.push(car.priceInr);
  }

  return RAW_CAR_DATA.map((car) => {
    const pool = compPools.get(`${car.make}:${car.model}`) || [car.priceInr];
    // Add realistic synthetic comp prices based on market deviations
    const syntheticComps = [
      Math.round(car.priceInr * 0.94),
      Math.round(car.priceInr * 0.98),
      car.priceInr,
      Math.round(car.priceInr * 1.03),
      Math.round(car.priceInr * 1.06),
      Math.round(car.priceInr * 0.96),
      Math.round(car.priceInr * 1.02),
    ];

    const priceRating = calculatePriceRating(car.priceInr, syntheticComps);

    // Build verification ladder based on seller type & inspection presence
    const isDealer = car.seller.type === "verified_dealer";
    const verificationLadder = evaluateVerificationLadder([
      {
        item: "identity",
        title: "Seller Identity",
        level: isDealer ? "partner_checked" : "document_seen",
        source: isDealer ? "Dealership GST & Business License" : "Aadhaar KYC + OTP",
      },
      {
        item: "ownership",
        title: "Registration & RC Status",
        level: "document_seen",
        source: "Vahan / Parivahan RTO Database Match",
      },
      {
        item: "insurance",
        title: "Insurance Policy",
        level: "document_seen",
        source: "Verified Policy Certificate",
      },
      {
        item: "odometer",
        title: "Odometer Integrity",
        level: isDealer ? "partner_checked" : "document_seen",
        source: "OEM Authorized Service Network History",
      },
      {
        item: "inspection",
        title: "160-Point Physical Inspection",
        level: car.inspection ? "partner_checked" : "declared",
        source: car.inspection ? "AutoBazaar Certified Inspection" : "Seller Declaration",
      },
    ]);

    return {
      ...car,
      priceRating,
      verificationLadder,
    };
  });
}
